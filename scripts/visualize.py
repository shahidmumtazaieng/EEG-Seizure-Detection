#!/usr/bin/env python3
from __future__ import annotations

from pathlib import Path

import matplotlib.pyplot as plt
import mne
import numpy as np
import pandas as pd
import streamlit as st

from eeg_seizure.visualization import merge_intervals


st.set_page_config(page_title="EEG seizure classification", layout="wide")
st.title("EEG seizure-classification results")
st.caption(
    "Academic/research visualization only. This prototype does not diagnose epilepsy "
    "or predict seizures clinically."
)

uploaded_predictions = st.file_uploader("Prediction CSV", type="csv")
raw_root_text = st.text_input("CHB-MIT raw-data folder", value="data/raw/chb-mit")
if uploaded_predictions is None:
    st.info("Upload a predictions CSV generated by the current training scripts.")
    st.stop()

try:
    predictions = pd.read_csv(uploaded_predictions)
except (OSError, pd.errors.ParserError, UnicodeDecodeError) as exc:
    st.error(f"Could not read the predictions CSV: {exc}")
    st.stop()

required_columns = {"group", "file", "window_start_sec", "window_sec", "y_true", "y_prob"}
missing_columns = required_columns.difference(predictions.columns)
if missing_columns:
    st.error(
        "This predictions CSV is missing interval metadata "
        f"({', '.join(sorted(missing_columns))}). Retrain using the current scripts to "
        "produce a CSV with EDF filenames and window timestamps."
    )
    st.stop()
if predictions.empty:
    st.error("The predictions CSV contains no windows.")
    st.stop()

numeric_columns = ["window_start_sec", "window_sec", "y_true", "y_prob"]
for column in numeric_columns:
    predictions[column] = pd.to_numeric(predictions[column], errors="coerce")
if predictions[numeric_columns].isna().any().any():
    st.error("The prediction CSV contains missing or non-numeric window values.")
    st.stop()
if not np.isfinite(predictions[numeric_columns].to_numpy(dtype=float)).all():
    st.error("The prediction CSV contains non-finite window values.")
    st.stop()
if (predictions["window_sec"] <= 0).any() or (predictions["window_start_sec"] < 0).any():
    st.error("Window starts must be non-negative and durations must be positive.")
    st.stop()
if not predictions["y_true"].isin([0, 1]).all():
    st.error("Ground-truth labels must be binary (0 or 1).")
    st.stop()
if not predictions["y_prob"].between(0, 1).all():
    st.error("Prediction probabilities must be between 0 and 1.")
    st.stop()
if predictions["group"].isna().any() or predictions["file"].isna().any():
    st.error("The prediction CSV contains missing patient or EDF filenames.")
    st.stop()

patients = sorted(predictions["group"].astype(str).unique())
patient = st.selectbox("Patient", patients)
patient_predictions = predictions[predictions["group"].astype(str) == patient].copy()
edf_names = sorted(patient_predictions["file"].astype(str).unique())
edf_name = st.selectbox("EDF recording", edf_names)
record_predictions = patient_predictions[patient_predictions["file"].astype(str) == edf_name]

raw_root = Path(raw_root_text).expanduser()
edf_path = raw_root / patient / edf_name
if not edf_path.is_file():
    matches = [
        path
        for path in raw_root.rglob(edf_name)
        if path.is_file() and path.parent.name == patient
    ] if raw_root.is_dir() else []
    if len(matches) != 1:
        st.error(
            f"Could not uniquely locate {edf_name} for {patient} under {raw_root}. "
            "Check the raw-data folder and patient-directory names."
        )
        st.stop()
    edf_path = matches[0]

try:
    raw = mne.io.read_raw_edf(str(edf_path), preload=False, verbose="ERROR")
except (OSError, ValueError, RuntimeError) as exc:
    st.error(f"Could not open EDF recording {edf_path}: {exc}")
    st.stop()

duration_sec = float(raw.n_times / raw.info["sfreq"])
eeg_indices = mne.pick_types(raw.info, eeg=True, exclude=[])
if len(eeg_indices) == 0:
    st.error("No EEG channels were found in this EDF recording.")
    st.stop()
channel_names = [raw.ch_names[index] for index in eeg_indices]
default_channels = channel_names[: min(4, len(channel_names))]

threshold = st.sidebar.slider("Prediction threshold", 0.0, 1.0, 0.5, 0.01)
view_duration = st.sidebar.slider(
    "Seconds to display", min_value=10, max_value=120, value=30, step=10
)
max_start = max(0.0, duration_sec - view_duration)
start_sec = st.sidebar.slider(
    "Start time (seconds)",
    min_value=0.0,
    max_value=float(max_start),
    value=0.0,
    step=1.0,
)
selected_channels = st.multiselect(
    "EEG channels",
    options=channel_names,
    default=default_channels,
)
if not selected_channels:
    st.warning("Select at least one EEG channel.")
    st.stop()

end_sec = min(duration_sec, start_sec + view_duration)
sample_rate = float(raw.info["sfreq"])
first_sample = int(start_sec * sample_rate)
last_sample = min(raw.n_times, int(end_sec * sample_rate))
try:
    signal = raw.get_data(
        picks=selected_channels,
        start=first_sample,
        stop=last_sample,
    )
    if sample_rate / 2 > 60:
        signal = mne.filter.notch_filter(
            signal, sfreq=sample_rate, freqs=[60.0], verbose="ERROR"
        )
    signal = mne.filter.filter_data(
        signal, sfreq=sample_rate, l_freq=0.5, h_freq=min(40.0, sample_rate / 2 - 1),
        verbose="ERROR",
    )
except (ValueError, RuntimeError) as exc:
    st.error(f"Could not read or filter the selected EEG segment: {exc}")
    st.stop()

times = np.arange(signal.shape[1], dtype=float) / sample_rate + start_sec
window_ends = record_predictions["window_start_sec"] + record_predictions["window_sec"]
window_pred = record_predictions["y_prob"] >= threshold
window_true = record_predictions["y_true"] >= 0.5

visible_predictions = record_predictions.loc[
    window_pred
    & (window_ends > start_sec)
    & (record_predictions["window_start_sec"] < end_sec)
]
visible_truth = record_predictions.loc[
    window_true
    & (window_ends > start_sec)
    & (record_predictions["window_start_sec"] < end_sec)
]

tp = int(np.sum(window_pred & window_true))
fp = int(np.sum(window_pred & ~window_true))
fn = int(np.sum(~window_pred & window_true))
tn = int(np.sum(~window_pred & ~window_true))
precision = tp / (tp + fp) if tp + fp else 0.0
recall = tp / (tp + fn) if tp + fn else 0.0
specificity = tn / (tn + fp) if tn + fp else 0.0

metric_cols = st.columns(6)
metric_cols[0].metric("TP windows", tp)
metric_cols[1].metric("FP windows", fp)
metric_cols[2].metric("FN windows", fn)
metric_cols[3].metric("TN windows", tn)
metric_cols[4].metric("Precision / sensitivity", f"{precision:.3f} / {recall:.3f}")
metric_cols[5].metric("Specificity", f"{specificity:.3f}")
st.caption(
    "Metrics above are window-level counts across the selected EDF; overlapping windows "
    "are correlated and these are not event-level clinical metrics."
)

fig, (signal_ax, probability_ax) = plt.subplots(
    2, 1, figsize=(14, 8), sharex=True, gridspec_kw={"height_ratios": [3, 1]}
)
offset_uv = 250.0
downsample = max(1, int(np.ceil(signal.shape[1] / 12000)))
for index, channel in enumerate(selected_channels):
    trace_uv = signal[index, ::downsample] * 1e6
    signal_ax.plot(
        times[::downsample],
        trace_uv + index * offset_uv,
        linewidth=0.6,
        label=channel,
    )
signal_ax.set_ylabel("EEG (µV, vertically offset)")
signal_ax.legend(loc="upper right", ncol=min(4, len(selected_channels)), fontsize="small")
signal_ax.grid(True, alpha=0.2)

predicted_intervals = merge_intervals(
    zip(
        visible_predictions["window_start_sec"],
        visible_predictions["window_start_sec"] + visible_predictions["window_sec"],
    )
)
annotated_intervals = merge_intervals(
    zip(
        visible_truth["window_start_sec"],
        visible_truth["window_start_sec"] + visible_truth["window_sec"],
    )
)
for interval_start, interval_end in predicted_intervals:
    signal_ax.axvspan(
        max(start_sec, interval_start),
        min(end_sec, interval_end),
        color="red",
        alpha=0.12,
    )
for interval_start, interval_end in annotated_intervals:
    signal_ax.axvspan(
        max(start_sec, interval_start),
        min(end_sec, interval_end),
        color="green",
        alpha=0.10,
    )

probability_ax.plot(
    record_predictions["window_start_sec"],
    record_predictions["y_prob"],
    color="navy",
    linewidth=0.8,
    label="Seizure probability",
)
probability_ax.axhline(threshold, color="red", linestyle="--", label="Threshold")
probability_ax.set_ylim(-0.02, 1.02)
probability_ax.set_ylabel("Probability")
probability_ax.set_xlabel("Time (seconds)")
probability_ax.set_xlim(start_sec, end_sec)
probability_ax.grid(True, alpha=0.2)
probability_ax.legend(loc="upper right")
fig.suptitle(f"{patient} — {edf_name}\nRed: model-positive windows | Green: annotated seizure windows")
fig.tight_layout()
st.pyplot(fig, clear_figure=True)
plt.close(fig)

with st.expander("Selected recording window predictions"):
    columns = [
        column
        for column in ("window_start_sec", "window_sec", "y_true", "y_prob", "fold")
        if column in record_predictions.columns
    ]
    st.dataframe(record_predictions[columns].sort_values("window_start_sec"), use_container_width=True)
